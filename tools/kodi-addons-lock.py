#!/usr/bin/env python3
"""Resolve device/kodi-addons.want into device/kodi-addons.list.

Run on a computer after editing the want file:  python3 tools/kodi-addons-lock.py
The want file names add-ons; dependencies are found here, once, and written out
with exact versions and sha256, so the device installs the same thing every time
and never resolves anything itself.

Want file lines:
  <id>                              latest from Kodi's official repository (Omega)
  <id> <version> <url> <sha256>     a zip from elsewhere, pinned by hand
Add-ons Kodi already ships (device/kodi-builtin.txt) are left out.
"""
import gzip
import hashlib
import io
import os
import re
import sys
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WANT = os.path.join(ROOT, "device", "kodi-addons.want")
OUT = os.path.join(ROOT, "device", "kodi-addons.list")
BUILTIN = os.path.join(ROOT, "device", "kodi-builtin.txt")
REPO = "https://mirrors.kodi.tv/addons/omega"


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "media-stick"}), timeout=60) as r:
        return r.read()


def vkey(v):
    return [int(x) if x.isdigit() else x for x in re.split(r"[.+~-]", v)]


def imports(addon_el):
    return [i.get("addon") for i in addon_el.findall("requires/import") if i.get("optional") != "true"]


builtin = set(open(BUILTIN).read().split())
index = {}
for a in ET.fromstring(gzip.decompress(get(REPO + "/addons.xml.gz"))).findall("addon"):
    i = a.get("id")
    if i not in index or vkey(a.get("version")) > vkey(index[i].get("version")):
        index[i] = a

pinned, order = {}, []
for line in open(WANT):
    line = line.split("#", 1)[0].split()
    if not line:
        continue
    if len(line) == 4:
        pinned[line[0]] = line[1:]
    order.append(line[0])

resolved, out, stack = {}, [], []


def resolve(i):
    if i in resolved or i in builtin or i.startswith("xbmc."):
        return
    if i in stack:
        sys.exit(f"dependency cycle: {' -> '.join(stack + [i])}")
    stack.append(i)
    if i in pinned:
        ver, url, sha = pinned[i]
        data = get(url)
        if hashlib.sha256(data).hexdigest() != sha:
            sys.exit(f"{i}: sha256 does not match the want file")
        z = zipfile.ZipFile(io.BytesIO(data))
        deps = imports(ET.fromstring(z.read(f"{i}/addon.xml")))
    else:
        if i not in index:
            sys.exit(f"{i}: not in {REPO} (needed by {stack[-2] if len(stack) > 1 else 'want file'})")
        a = index[i]
        ver = a.get("version")
        url = f"{REPO}/{i}/{urllib.parse.quote(f'{i}-{ver}.zip')}"
        sha = get(url + ".sha256").decode().split()[0]
        deps = imports(a)
    for d in deps:
        resolve(d)
    stack.pop()
    resolved[i] = (ver, url, sha)
    out.append(i)


for i in order:
    resolve(i)

with open(OUT, "w") as f:
    f.write("# Generated by tools/kodi-addons-lock.py from device/kodi-addons.want. Do not edit.\n")
    f.write("# Dependencies come before what needs them.\n# id version url sha256\n")
    for i in out:
        f.write(" ".join((i,) + resolved[i]) + "\n")
print(f"{len(out)} add-ons -> {os.path.relpath(OUT, ROOT)}")
